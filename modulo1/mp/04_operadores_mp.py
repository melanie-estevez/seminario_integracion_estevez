cafe = 15
pastel = 20

print("SWEET COFFEE")

print("Suma")
print(cafe, "+", pastel, "=", cafe + pastel)

print("Resta")
print(cafe, "-", pastel, "=", cafe - pastel)

print("Multiplicación")
print(cafe, "*", pastel, "=", cafe * pastel)

print("División")
print(cafe, "/", pastel, "=", cafe / pastel)

print("División entera")
print(cafe, "//", pastel, "=", cafe // pastel)

print("Módulo")
print(cafe, "%", pastel, "=", cafe % pastel)

print("\nOperadores de asignación")
print("====================================")

ventas = 10

ventas += 5
print("ventas += 5 =", ventas)

ventas -= 3
print("ventas -= 3 =", ventas)

ventas *= 2
print("ventas *= 2 =", ventas)

ventas //= 2
print("ventas //= 2 =", ventas)

ventas **= 2
print("ventas **= 2 =", ventas)